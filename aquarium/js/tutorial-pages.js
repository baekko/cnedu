export const TUTORIAL_COPY = Object.fromEntries(
 Object.entries(PAGES).map(([place, pages]) => [place, pages.map(([, , caption]) => caption)]),
);

export function groupTutorial(tutorial, place) {
 const pages = PAGES[place];
 const pageByStep = new Map(pages.flatMap(([steps], page) => steps.map(step => [step, page])));
 for (const step of tutorial.seq) step.s = pageByStep.get(step.s);
 tutorial.titles = pages.map(([, title]) => title);
 tutorial.total = pages.length;
 return tutorial;
}
